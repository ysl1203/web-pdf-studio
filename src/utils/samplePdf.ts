import { PDFDocument, rgb, StandardFonts } from 'pdf-lib';

export async function createSamplePdf(): Promise<Uint8Array> {
  const pdfDoc = await PDFDocument.create();

  // Load standard fonts
  const fontHelveticaBold = await pdfDoc.embedFont(StandardFonts.HelveticaBold);
  const fontHelvetica = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const fontCourier = await pdfDoc.embedFont(StandardFonts.Courier);

  // Page 1: Welcome & Overview
  const page1 = pdfDoc.addPage([595.28, 841.89]); // A4 dimensions
  const { width, height } = page1.getSize();

  // Swiss Editorial Header Banner (Deep Obsidian + Vermilion Accent Rule)
  page1.drawRectangle({
    x: 0,
    y: height - 130,
    width: width,
    height: 130,
    color: rgb(0.095, 0.098, 0.115), // #18191D
  });
  page1.drawRectangle({
    x: 0,
    y: height - 134,
    width: width,
    height: 4,
    color: rgb(0.788, 0.231, 0.169), // #C93B2B Swiss Vermilion
  });

  page1.drawText('Web PDF Studio', {
    x: 42,
    y: height - 62,
    size: 28,
    font: fontHelveticaBold,
    color: rgb(0.985, 0.98, 0.965),
  });

  page1.drawText('Editorial Paper & Vector Workbench · Local Document Suite', {
    x: 42,
    y: height - 92,
    size: 12.5,
    font: fontHelvetica,
    color: rgb(0.76, 0.74, 0.71),
  });

  // Section 1
  page1.drawText('1. About This Application', {
    x: 42,
    y: height - 172,
    size: 16,
    font: fontHelveticaBold,
    color: rgb(0.095, 0.095, 0.11),
  });

  const introLines = [
    'Web PDF Studio provides complete local PDF editing, direct text rewriting, and format conversion.',
    'All processing stays on your device: zero cloud uploads, instant preview, and crisp vector export.',
    'Exported documents follow ISO PDF & OOXML standards for Office, WPS, Acrobat, and Preview.',
  ];

  let currentY = height - 196;
  for (const line of introLines) {
    page1.drawText(line, {
      x: 42,
      y: currentY,
      size: 10.5,
      font: fontHelvetica,
      color: rgb(0.28, 0.28, 0.31),
    });
    currentY -= 18;
  }

  // Feature Cards
  const cards = [
    { title: 'Interactive Annotations', desc: 'Rewrite source text, draw arrows/shapes, highlight & erase smoothly' },
    { title: 'Digital Signatures & Stamps', desc: 'HiDPI freehand signatures, stamp seals, and transparent image inserts' },
    { title: 'Rotation-Synced Page Tree', desc: 'Reorder, rotate 90/180/270 deg, duplicate, merge, and insert blank pages' },
    { title: 'Office & Image Pipeline', desc: 'Export to PDF, Word (.docx), high-DPI PNG/JPEG ZIP, or Markdown' },
  ];

  currentY -= 16;
  page1.drawText('2. Core Capabilities Matrix', {
    x: 42,
    y: currentY,
    size: 16,
    font: fontHelveticaBold,
    color: rgb(0.095, 0.095, 0.11),
  });

  currentY -= 30;
  for (let i = 0; i < cards.length; i++) {
    const card = cards[i];
    const cardY = currentY - i * 56;

    // Warm paper card background
    page1.drawRectangle({
      x: 42,
      y: cardY - 36,
      width: width - 84,
      height: 48,
      color: rgb(0.98, 0.975, 0.965),
      borderColor: rgb(0.86, 0.84, 0.80),
      borderWidth: 1,
    });

    // Swiss Vermilion indicator bar
    page1.drawRectangle({
      x: 42,
      y: cardY - 36,
      width: 4,
      height: 48,
      color: rgb(0.788, 0.231, 0.169),
    });

    page1.drawText(card.title, {
      x: 58,
      y: cardY - 12,
      size: 12,
      font: fontHelveticaBold,
      color: rgb(0.095, 0.095, 0.11),
    });

    page1.drawText(card.desc, {
      x: 58,
      y: cardY - 28,
      size: 10,
      font: fontHelvetica,
      color: rgb(0.38, 0.38, 0.42),
    });
  }

  // Footer on page 1
  page1.drawText('Page 1 of 2  -  Generated by Web PDF Studio Engine', {
    x: 40,
    y: 30,
    size: 9,
    font: fontCourier,
    color: rgb(0.55, 0.6, 0.65),
  });

  // Page 2: Sample Structured Report (for Word / Tables export testing)
  const page2 = pdfDoc.addPage([595.28, 841.89]);
  
  page2.drawText('Sample Financial & Project Summary', {
    x: 40,
    y: height - 60,
    size: 22,
    font: fontHelveticaBold,
    color: rgb(0.1, 0.15, 0.25),
  });

  page2.drawText('Q4 Quarterly Performance and Deliverables Overview', {
    x: 40,
    y: height - 85,
    size: 12,
    font: fontHelvetica,
    color: rgb(0.4, 0.45, 0.55),
  });

  // Table header (Editorial Obsidian)
  const tableY = height - 140;
  page2.drawRectangle({
    x: 40,
    y: tableY,
    width: width - 80,
    height: 26,
    color: rgb(0.10, 0.10, 0.12),
  });
  page2.drawRectangle({
    x: 40,
    y: tableY,
    width: width - 80,
    height: 2,
    color: rgb(0.788, 0.231, 0.169),
  });

  page2.drawText('Item / Deliverable', { x: 50, y: tableY + 8, size: 10, font: fontHelveticaBold, color: rgb(1, 1, 1) });
  page2.drawText('Category', { x: 230, y: tableY + 8, size: 10, font: fontHelveticaBold, color: rgb(1, 1, 1) });
  page2.drawText('Status', { x: 370, y: tableY + 8, size: 10, font: fontHelveticaBold, color: rgb(1, 1, 1) });
  page2.drawText('Value ($)', { x: 480, y: tableY + 8, size: 10, font: fontHelveticaBold, color: rgb(1, 1, 1) });

  // Table rows
  const tableRows = [
    { item: 'PDF Viewer Architecture', cat: 'Frontend Core', status: 'Completed', val: '$12,500' },
    { item: 'WYSIWYG Annotation Layer', cat: 'Canvas Engine', status: 'Completed', val: '$18,200' },
    { item: 'Word (.docx) Export Engine', cat: 'Converter', status: 'Verified', val: '$9,800' },
    { item: 'High-DPI Image ZIP Packager', cat: 'Export Suite', status: 'Completed', val: '$6,400' },
    { item: 'Standardized PDF Synthesizer', cat: 'pdf-lib Core', status: 'Completed', val: '$14,100' },
  ];

  let rowY = tableY - 26;
  tableRows.forEach((row, idx) => {
    // alternating background
    if (idx % 2 === 0) {
      page2.drawRectangle({
        x: 40,
        y: rowY,
        width: width - 80,
        height: 26,
        color: rgb(0.97, 0.98, 0.99),
      });
    }

    page2.drawRectangle({
      x: 40,
      y: rowY,
      width: width - 80,
      height: 26,
      borderColor: rgb(0.88, 0.9, 0.94),
      borderWidth: 0.5,
    });

    page2.drawText(row.item, { x: 50, y: rowY + 8, size: 10, font: fontHelvetica, color: rgb(0.15, 0.2, 0.3) });
    page2.drawText(row.cat, { x: 230, y: rowY + 8, size: 9, font: fontHelvetica, color: rgb(0.35, 0.4, 0.5) });
    page2.drawText(row.status, { x: 370, y: rowY + 8, size: 9, font: fontHelveticaBold, color: rgb(0.1, 0.55, 0.25) });
    page2.drawText(row.val, { x: 480, y: rowY + 8, size: 10, font: fontCourier, color: rgb(0.1, 0.2, 0.4) });

    rowY -= 26;
  });

  // Signature Block
  const sigY = 120;
  page2.drawText('Authorized Signature:', {
    x: 40,
    y: sigY + 40,
    size: 11,
    font: fontHelveticaBold,
    color: rgb(0.2, 0.25, 0.35),
  });

  page2.drawLine({
    start: { x: 40, y: sigY },
    end: { x: 260, y: sigY },
    thickness: 1,
    color: rgb(0.5, 0.55, 0.65),
  });

  page2.drawText('Date: 2026-11-15', {
    x: 350,
    y: sigY + 40,
    size: 11,
    font: fontHelveticaBold,
    color: rgb(0.2, 0.25, 0.35),
  });

  page2.drawLine({
    start: { x: 350, y: sigY },
    end: { x: 520, y: sigY },
    thickness: 1,
    color: rgb(0.5, 0.55, 0.65),
  });

  // Footer on page 2
  page2.drawText('Page 2 of 2  -  Generated by Web PDF Studio Engine', {
    x: 40,
    y: 30,
    size: 9,
    font: fontCourier,
    color: rgb(0.55, 0.6, 0.65),
  });

  return await pdfDoc.save();
}
